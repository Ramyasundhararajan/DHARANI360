# ============================================================================
# Cross-register linking
# ----------------------------------------------------------------------------
# Field NAMES that represent a shared real-world key across multiple forms
# (a lead, a client, an agent, a property, a transaction, an employee, a
# vendor, an asset...). A record's "Related Records" panel is built purely
# from this: for each of a record's fields whose name appears here, every
# OTHER register that has a same-named field is searched for a matching
# value. No per-form wiring needed - add a field called "property_ref" to
# form #77 and it automatically links up with every other "property_ref".
# ============================================================================
LINK_FIELD_NAMES = {
    "lead_id", "client_name", "agent_name", "agent_master", "property_ref",
    "transaction_ref", "employee_name", "vendor_name", "asset_ref",
    "owner_name", "referred_by", "poa_holder",
    # Marketing: one campaign reference threads a request, its budget, its
    # creative, its ads, its leads and its closure together.
    "campaign_ref",
}

# name -> list of form codes that contain a field with that exact name
FIELD_TO_FORMS = {}
for _f in FORMS:
    for _fld in _f["fields"]:
        if _fld["name"] in LINK_FIELD_NAMES:
            FIELD_TO_FORMS.setdefault(_fld["name"], []).append(_f["code"])


def linkable_fields(form_code):
    """Field names on this form that participate in cross-register linking."""
    form = FORMS_BY_CODE[form_code]
    return [f["name"] for f in form["fields"] if f["name"] in LINK_FIELD_NAMES]


# ============================================================================
# Automatic field grouping (used to lay out every form/record view into
# readable sections without hand-tagging 600+ fields one by one).
# ============================================================================
SECTION_ORDER = ["Identification & Reference", "People & Parties", "Dates",
                  "Financial", "Figures & Quantities",
                  "Status & Classification", "Details & Notes"]

_ID_HINTS = ("_ref", "_no", "_number", "reference", "_id", "licence", "license", "doc_no")
_PEOPLE_HINTS = ("name", "contact", "phone", "email", "person")
_MONEY_HINTS = ("amount", "price", "salary", "commission", "fee", "cost", "value", "budget",
                 "rent", "balance", "total", "payment", "paid", "aed", "deposit", "advance",
                 "charge", "income", "expense", "revenue", "gross", "net", "premium")


def classify_field(field):
    name = field["name"].lower()
    ftype = field["type"]
    if any(h in name for h in _ID_HINTS):
        return "Identification & Reference"
    if any(h in name for h in _PEOPLE_HINTS):
        return "People & Parties"
    if ftype == "date":
        return "Dates"
    if ftype == "number":
        # Not every number is money - a call duration or a floor count was
        # landing under "Financial", which read as wrong on screen.
        return "Financial" if any(h in name for h in _MONEY_HINTS) else "Figures & Quantities"
    if ftype == "select":
        return "Status & Classification"
    return "Details & Notes"


def group_fields(fields):
    """Return [(section_name, [field, ...]), ...] in a fixed, readable order."""
    buckets = {s: [] for s in SECTION_ORDER}
    for f in fields:
        # setdefault so a future new section name can never 500 a whole form
        buckets.setdefault(classify_field(f), []).append(f)
    return [(s, buckets[s]) for s in SECTION_ORDER if buckets[s]]
